package settings

import (
	"encoding/json"
	"fmt"
	"reflect"
	"strconv"
)

// Fact is one row of the generated settings reference: a key of the Settings
// struct and every tag that describes it. Optional facts are pointers or
// omitted when empty, so a row carries only what the schema declares: a present
// zero minimum and a present empty-string default are facts, an absent one is
// not.
type Fact struct {
	Namespace     string   `json:"namespace"`
	Key           string   `json:"key"`
	Type          string   `json:"type"`
	Items         string   `json:"items,omitempty"`
	Default       any      `json:"default,omitempty"`
	Enum          []string `json:"enum,omitempty"`
	Pattern       string   `json:"pattern,omitempty"`
	Minimum       *float64 `json:"minimum,omitempty"`
	Maximum       *float64 `json:"maximum,omitempty"`
	Nullable      *bool    `json:"nullable,omitempty"`
	Doc           string   `json:"doc"`
	Domain        string   `json:"domain"`
	ClientVisible bool     `json:"client_visible"`
}

// Facts walks the Settings struct and returns one row per key, in declaration
// order. It reads the same tags Defaults and Namespaces read, so the reference
// and the engine cannot disagree; a malformed tag panics, as Defaults does.
func Facts() []Fact {
	var out []Fact
	t := reflect.TypeOf(Settings{})
	namespaces := Namespaces()
	for i := 0; i < t.NumField(); i++ {
		ns := namespaces[i]
		nsType := t.Field(i).Type
		for j := 0; j < nsType.NumField(); j++ {
			out = append(out, factOf(ns, nsType.Field(j)))
		}
	}
	return out
}

func factOf(ns Namespace, f reflect.StructField) Fact {
	where := ns.Name + "." + jsonName(f)
	typ, items := jsonType(f.Type)
	fact := Fact{
		Namespace:     ns.Name,
		Key:           jsonName(f),
		Type:          typ,
		Items:         items,
		Pattern:       f.Tag.Get("pattern"),
		Doc:           f.Tag.Get("doc"),
		Domain:        ns.Domain,
		ClientVisible: ns.ClientVisible,
	}
	if tag, ok := f.Tag.Lookup("default"); ok {
		v, err := fieldDefault(tag, f.Type)
		if err != nil {
			panic("settings: bad default tag on " + where + ": " + err.Error())
		}
		fact.Default = v
	}
	if tag := f.Tag.Get("enum"); tag != "" {
		fact.Enum = splitComma(tag)
	}
	fact.Minimum = boundTag(where, f, "minimum")
	fact.Maximum = boundTag(where, f, "maximum")
	if tag, ok := f.Tag.Lookup("nullable"); ok {
		b, err := strconv.ParseBool(tag)
		if err != nil {
			panic("settings: bad nullable tag on " + where + ": " + err.Error())
		}
		fact.Nullable = &b
	}
	return fact
}

// boundTag reads a minimum or maximum tag, nil when the field declares none.
func boundTag(where string, f reflect.StructField, name string) *float64 {
	tag, ok := f.Tag.Lookup(name)
	if !ok {
		return nil
	}
	v, err := strconv.ParseFloat(tag, 64)
	if err != nil {
		panic("settings: bad " + name + " tag on " + where + ": " + err.Error())
	}
	return &v
}

// jsonType names a field's JSON Schema type, and an array's element type.
func jsonType(t reflect.Type) (typ, items string) {
	switch t.Kind() {
	case reflect.String:
		return "string", ""
	case reflect.Bool:
		return "boolean", ""
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		return "integer", ""
	case reflect.Float32, reflect.Float64:
		return "number", ""
	case reflect.Slice:
		elem, _ := jsonType(t.Elem())
		return "array", elem
	}
	panic(fmt.Sprintf("settings: no JSON type for kind %s", t.Kind()))
}

// FactsJSON renders Facts as the committed docs/src/generated/settings.json,
// the input of the docs' settings reference (cmd/settingsgen writes it; the
// drift test fails when it goes stale).
func FactsJSON() ([]byte, error) {
	doc := struct {
		Comment  string `json:"//"`
		Settings []Fact `json:"settings"`
	}{
		Comment:  "generated by make gen (cmd/settingsgen); do not edit",
		Settings: Facts(),
	}
	out, err := json.MarshalIndent(doc, "", " ")
	if err != nil {
		return nil, fmt.Errorf("settings facts: marshal: %w", err)
	}
	return append(out, '\n'), nil
}
