package mcpgen

import (
	"fmt"
	"regexp"
	"strings"

	"github.com/hyperscaleav/omniglass/internal/mcp/skills"
	"github.com/hyperscaleav/omniglass/internal/mcp/tooldef"
)

// toolRef is a tool reference in a skill body, as the skills package parses it.
var toolRef = regexp.MustCompile("`tool:([a-z0-9-]+)`")

// RenderSkills is the docs reference page for the agent skills (#2026): an
// index, then each skill with its arguments, the tools it uses with their
// gates, the permissions those gates add up to, and its workflow, every tool
// reference linked to the tool's entry on the tools page. Tools and
// permissions are read from the catalog, never from the skill.
func RenderSkills(defs []tooldef.Def, sk []skills.Skill) []byte {
	byName := map[string]tooldef.Def{}
	for _, d := range defs {
		byName[d.Name] = d
	}
	var b strings.Builder
	b.WriteString(`---
title: MCP skills
description: "Every skill the omniglass MCP server serves as a prompt, generated from the skill files so it never drifts from what an agent is handed."
---

<!-- Generated by cmd/mcpgen from internal/mcp/skills. Do not edit by hand; run ` + "`make gen`" + `. -->

A skill is a workflow: the house way to do one whole job (triage an alarm, troubleshoot a component)
with the [MCP tools](/reference/mcp/). The server serves each one as an MCP prompt, so an agent's
client lists them beside the tools, and ` + "`omniglass mcp skill <name>`" + ` prints one for an agent
that reads skill files instead. A skill runs nothing itself: it tells the agent which tools to call,
and each call is gated, scoped and audited as any other. The tools and permissions below are read
from the tool catalog, so a skill can never claim less than its tools need. To use one, see
[connect an agent](/guides/agents/#skills).

`)
	fmt.Fprintf(&b, "%d skills.\n\n", len(sk))
	b.WriteString("| Skill | Category | What it does |\n|---|---|---|\n")
	for _, s := range sk {
		fmt.Fprintf(&b, "| [`%s`](#%s) | %s | %s |\n", s.Name, s.Name, s.Category, cell(s.Description))
	}
	for _, s := range sk {
		fmt.Fprintf(&b, "\n## `%s`\n\n%s\n\n", s.Name, s.Description)
		fmt.Fprintf(&b, "- Category: %s\n", s.Category)
		if len(s.Arguments) == 0 {
			b.WriteString("- Arguments: none\n")
		} else {
			b.WriteString("- Arguments:\n")
			for _, a := range s.Arguments {
				req := "optional"
				if a.Required {
					req = "required"
				}
				fmt.Fprintf(&b, "  - `%s` (%s): %s\n", a.Name, req, a.Description)
			}
		}
		var tools, perms []string
		seen := map[string]bool{}
		for _, t := range s.Tools {
			d := byName[t]
			tools = append(tools, fmt.Sprintf("[`%s`](/reference/mcp/#%s) (%s)", t, t, gateCell(d.Permission)))
			if d.Permission != "" && !seen[d.Permission] {
				seen[d.Permission] = true
				perms = append(perms, "`"+d.Permission+"`")
			}
		}
		fmt.Fprintf(&b, "- Tools: %s\n", strings.Join(tools, ", "))
		if len(perms) == 0 {
			b.WriteString("- Permissions: authn only\n")
		} else {
			fmt.Fprintf(&b, "- Permissions: %s\n", strings.Join(perms, ", "))
		}
		b.WriteString("\n" + skillBody(s.Body))
	}
	return []byte(b.String())
}

// skillBody is a skill's workflow as it sits under the skill's own heading:
// every heading two levels deeper (code fences left alone), every tool
// reference a link to the tool.
func skillBody(body string) string {
	var out []string
	inFence := false
	for _, line := range strings.Split(strings.TrimRight(body, "\n"), "\n") {
		if strings.HasPrefix(line, "```") {
			inFence = !inFence
		}
		if !inFence && strings.HasPrefix(line, "#") {
			line = "##" + line
		}
		if !inFence {
			line = toolRef.ReplaceAllString(line, "[`$1`](/reference/mcp/#$1)")
		}
		out = append(out, line)
	}
	return strings.Join(out, "\n") + "\n"
}
