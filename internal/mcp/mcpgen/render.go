// RenderGo renders the catalog as the Go source internal/mcp serves from: one
// tooldef.Def per tool, gofmt-clean.
func RenderGo(defs []tooldef.Def) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by cmd/mcpgen from api/openapi.json. DO NOT EDIT.\n\n")
	b.WriteString("package mcp\n\n")
	b.WriteString("import \"github.com/hyperscaleav/omniglass/internal/mcp/tooldef\"\n\n")
	b.WriteString("// catalog is every tool the MCP server serves: one per API operation stamped\n")
	b.WriteString("// " + tooldef.Extension + " in Go, regenerated by `make gen` (#1162, ADR-1162).\n")
	b.WriteString("var catalog = []tooldef.Def{\n")
	for _, d := range defs {
		b.WriteString("\t{\n")
		field := func(name, val string) { fmt.Fprintf(&b, "\t\t%s: %s,\n", name, val) }
		field("Name", strconv.Quote(d.Name))
		field("Title", strconv.Quote(d.Title))
		field("Description", strconv.Quote(d.Description))
		field("Method", strconv.Quote(d.Method))
		field("Path", strconv.Quote(d.Path))
		field("Permission", strconv.Quote(d.Permission))
		for _, s := range []struct {
			name string
			v    []string
		}{{"PathParams", d.PathParams}, {"QueryParams", d.QueryParams}, {"BodyParams", d.BodyParams}} {
			if len(s.v) == 0 {
				continue
			}
			q := make([]string, len(s.v))
			for i, x := range s.v {
				q[i] = strconv.Quote(x)
			}
			field(s.name, "[]string{"+strings.Join(q, ", ")+"}")
		}
		if d.BodyWhole {
			field("BodyWhole", "true")
		}
		a := d.Annotations
		field("Annotations", fmt.Sprintf("tooldef.Annotations{ReadOnly: %t, Destructive: %t, Idempotent: %t, OpenWorld: %t}", a.ReadOnly, a.Destructive, a.Idempotent, a.OpenWorld))
		field("InputSchema", strconv.Quote(d.InputSchema))
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	return format.Source([]byte(b.String()))
}

// RenderDoc renders the docs reference page for the catalog: what each tool
// does, the route and gate behind it, what a client may assume of it, and its
// arguments.
func RenderDoc(defs []tooldef.Def) []byte {
	var b strings.Builder
	b.WriteString(`---
title: MCP tools
description: "Every tool the omniglass MCP server serves, generated from the API so it never drifts from the routes."
---

<!-- Generated by cmd/mcpgen from api/openapi.json. Do not edit by hand; run ` + "`make gen`" + `. -->

Every tool the omniglass MCP server serves, generated from the [API](/reference/api/) by the same
` + "`make gen`" + ` that generates the CLI. A tool is an API operation stamped for MCP in the server's Go
source: calling it runs that route with the caller's token, so its gate, its scope and its audit row
are the route's own, and the row records that it came over MCP. To connect an agent, see
[connect an agent](/guides/agents/).

Each tool says what a client may assume of it, from one rule over the route's method and gate:

- **read-only**: changes nothing (a read, or a preview gated by a read). A client may run it freely.
- **destructive**: overwrites or removes something, or acts on a component. A client should confirm it with
  its user.
- **idempotent**: calling it again with the same arguments changes nothing more.
- **open-world**: reaches outside omniglass.

A tool that is not read-only and not destructive adds something (a create).

`)
	fmt.Fprintf(&b, "%d tools.\n\n", len(defs))
	b.WriteString("| Tool | What it does | Gate | Assume |\n|---|---|---|---|\n")
	for _, d := range defs {
		fmt.Fprintf(&b, "| [`%s`](#%s) | %s | %s | %s |\n", d.Name, d.Name, cell(d.Title), gateCell(d.Permission), assumes(d.Annotations))
	}
	for _, d := range defs {
		fmt.Fprintf(&b, "\n## `%s`\n\n", d.Name)
		fmt.Fprintf(&b, "%s\n\n", d.Title)
		fmt.Fprintf(&b, "%s\n\n", d.Description)
		fmt.Fprintf(&b, "- Route: `%s /api/v1%s`\n", d.Method, d.Path)
		fmt.Fprintf(&b, "- Gate: %s\n", gateCell(d.Permission))
		fmt.Fprintf(&b, "- Assume: %s\n", assumes(d.Annotations))
		args := arguments(d)
		if len(args) == 0 {
			b.WriteString("- Arguments: none\n")
			continue
		}
		b.WriteString("\n| Argument | Type | Required | Description |\n|---|---|---|---|\n")
		for _, a := range args {
			req := "no"
			if a.required {
				req = "yes"
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", a.name, a.typ, req, cell(a.description))
		}
	}
	return []byte(b.String())
}

func gateCell(permission string) string {
	if permission == "" {
		return "authn only"
	}
	return "`" + permission + "`"
}

func assumes(a tooldef.Annotations) string {
	var out []string
	if a.ReadOnly {
		out = append(out, "read-only")
	}
	if a.Destructive {
		out = append(out, "destructive")
	}
	if a.Idempotent {
		out = append(out, "idempotent")
	}
	if a.OpenWorld {
		out = append(out, "open-world")
	}
	if len(out) == 0 {
		return "adds"
	}
	return strings.Join(out, ", ")
}

// cell holds a string to one markdown table cell: a pipe escaped, a newline
// folded to a space.
func cell(s string) string {
	s = strings.ReplaceAll(s, "|", `\|`)
	s = strings.ReplaceAll(s, "\r\n", " ")
	return strings.ReplaceAll(s, "\n", " ")
}

type argument struct {
	name, typ, description string
	required               bool
}

// arguments reads a tool's arguments back out of its input schema, sorted by
// name, for the docs table.
func arguments(d tooldef.Def) []argument {
	var schema struct {
		Properties map[string]map[string]any `json:"properties"`
		Required   []string                  `json:"required"`
	}
	if err := json.Unmarshal([]byte(d.InputSchema), &schema); err != nil {
		return nil
	}
	req := map[string]bool{}
	for _, r := range schema.Required {
		req[r] = true
	}
	var out []argument
	for name, p := range schema.Properties {
		desc, _ := p["description"].(string)
		out = append(out, argument{name: name, typ: typeOf(p), description: desc, required: req[name]})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].name < out[j].name })
	return out
}

// typeOf names a schema's JSON type for the docs: the type, or its non-null
// member for a nullable one, or "any".
func typeOf(p map[string]any) string {
	switch t := p["type"].(type) {
	case string:
		return t
	case []any:
		var names []string
		for _, x := range t {
			if s, ok := x.(string); ok && s != "null" {
				names = append(names, s)
			}
		}
		if len(names) > 0 {
			return strings.Join(names, " or ")
		}
	}
	return "any"
}
