// Package notify is the send pipeline of a notification (#618): the webhook
// envelope a receiver gets, and the request that carries it, built in the
// page's order: render the body, then sign the rendered bytes, then send.
// Pure: it builds a request and never sends one (internal/egress sends), so
// the bytes a receiver verifies are the bytes built here, tested without a
// network.
package notify

import (
	"crypto/hmac"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"net/http"
	"reflect"
	"strconv"
	"time"

	"github.com/danielgtaylor/huma/v2"

	"github.com/hyperscaleav/omniglass/internal/egress"
)

// EnvelopeVersion is the webhook body's version. A change a receiver must
// handle differently is a new version, never an edit to this one.
const EnvelopeVersion = 1

// The headers a webhook delivery carries. The signature scheme is the one the
// inbound hmac webhook verifies (ADR-1024): sha256 over the signed timestamp,
// a ".", and the body, hex-encoded behind "sha256=", so a receiver that
// verifies an Omniglass-shaped sender verifies this one, Omniglass included.
const (
	HeaderSignature   = "X-Omniglass-Signature"
	HeaderTimestamp   = "X-Omniglass-Timestamp"
	HeaderEvent       = "X-Omniglass-Event"
	HeaderIdempotency = "Idempotency-Key"
	SignaturePrefix   = "sha256="
	SignatureSep      = "."
)

// Envelope is the JSON body of a webhook notification. Its templates render
// strings (subject, text); the body itself is this fixed shape, so an
// operator's template can never produce an invalid one.
type Envelope struct {
	Version int    `json:"version" doc:"The envelope version; this document describes version 1"`
	ID      string `json:"id" doc:"The notification's uuid, the same on every attempt; the Idempotency-Key header carries it too, so a receiver can drop a redelivery"`
	Type    string `json:"type" doc:"The notification type that rendered it, by name"`
	// Transition is the alarm edge, or "test" for a target's :test send.
	Transition string            `json:"transition" enum:"raised,cleared,test" doc:"The alarm edge the message is about; test for a target's :test send, which is about no alarm"`
	Subject    string            `json:"subject" doc:"The rendered subject, one line"`
	Text       string            `json:"text" doc:"The rendered text"`
	AlarmID    string            `json:"alarm_id,omitempty" doc:"The alarm's uuid; absent on a test send"`
	Facts      map[string]string `json:"facts" doc:"The alarm facts the templates read, every key present (an absent fact is the empty string): the same map a template renders over"`
}

// Credential is what a target signs or authenticates with, unsealed from its
// bound secret: an hmac key (the hmac-key secret type) or a bearer token (the
// bearer-token type), at most one. Never printed.
type Credential struct {
	HMACKey     string
	BearerToken string
}

// String never renders a credential.
func (Credential) String() string { return "notification credential" }

// Sign is the signature over ts, the separator and body under key: hex-encoded
// hmac-sha256, behind its prefix.
func Sign(key string, ts int64, body []byte) string {
	m := hmac.New(sha256.New, []byte(key))
	m.Write([]byte(strconv.FormatInt(ts, 10)))
	m.Write([]byte(SignatureSep))
	m.Write(body)
	return SignaturePrefix + hex.EncodeToString(m.Sum(nil))
}

// ErrEnvelope is an envelope that cannot be encoded.
var ErrEnvelope = errors.New("notify: envelope does not encode")

// Build renders env to its bytes and builds the request that carries it to
// url: the body first, the signature over exactly those bytes, then the
// headers. now stamps the signed timestamp.
func Build(url string, env Envelope, cred Credential, now time.Time) (egress.Request, error) {
	env.Version = EnvelopeVersion
	if env.Facts == nil {
		env.Facts = map[string]string{}
	}
	body, err := json.Marshal(env)
	if err != nil {
		return egress.Request{}, fmt.Errorf("%w: %v", ErrEnvelope, err)
	}
	h := http.Header{}
	h.Set("Content-Type", "application/json")
	h.Set("User-Agent", "Omniglass-Notify/1")
	h.Set(HeaderEvent, "notification")
	h.Set(HeaderIdempotency, env.ID)
	ts := now.Unix()
	h.Set(HeaderTimestamp, strconv.FormatInt(ts, 10))
	if cred.HMACKey != "" {
		h.Set(HeaderSignature, Sign(cred.HMACKey, ts, body))
	}
	if cred.BearerToken != "" {
		h.Set("Authorization", "Bearer "+cred.BearerToken)
	}
	return egress.Request{URL: url, Header: h, Body: body}, nil
}

// EnvelopeSchemaJSON renders the envelope's JSON Schema from the struct above
// (docs/src/generated/notification-envelope.json, cmd/labelgen), so the
// documented payload is the sent payload.
func EnvelopeSchemaJSON() ([]byte, error) {
	reg := huma.NewMapRegistry("#/$defs/", huma.DefaultSchemaNamer)
	s := reg.Schema(reflect.TypeFor[Envelope](), false, "")
	doc := map[string]any{
		"//":          "generated by make gen (cmd/labelgen) from internal/notify.Envelope; do not edit",
		"$schema":     "https://json-schema.org/draft/2020-12/schema",
		"title":       "Omniglass webhook notification, version " + strconv.Itoa(EnvelopeVersion),
		"type":        s.Type,
		"properties":  s.Properties,
		"required":    s.Required,
		"description": "The JSON body of a webhook notification. Headers: " + HeaderIdempotency + " (the id), " + HeaderTimestamp + " (unix seconds), " + HeaderSignature + " (" + SignaturePrefix + "hex hmac-sha256 over timestamp" + SignatureSep + "body, when the target binds an hmac-key secret), " + HeaderEvent + ": notification.",
	}
	out, err := json.MarshalIndent(doc, "", " ")
	if err != nil {
		return nil, err
	}
	return append(out, '\n'), nil
}
