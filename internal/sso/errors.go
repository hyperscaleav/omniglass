package sso

import (
	"fmt"
	"strings"
)

// ErrorCode is why a sign-in or a self-link came back refused (#2362). The
// callback redirects to the console with ?sso_error=<code>, one of a closed
// set, and the console shows its own fixed message for it (an unknown code,
// one generic message), so a crafted link can never put words of its own on
// the sign-in page. The detail (the identity the provider vouched for, the
// provider's own error, a verification failure) stays in the server's log
// line for the refusal, never in the URL.
type ErrorCode string

// The refusal codes, each one refusal path of the start route and the
// callback.
const (
	// ErrNotConfigured: no provider is configured under the name the sign-in
	// started with, or it was turned off before the callback.
	ErrNotConfigured ErrorCode = "not_configured"
	// ErrUnreachable: the provider's discovery or key set could not be read
	// (unreachable, refused by the egress policy, or misconfigured).
	ErrUnreachable ErrorCode = "unreachable"
	// ErrState: the callback's state is unknown, expired or already spent.
	ErrState ErrorCode = "state"
	// ErrBrowser: the callback came to a browser that did not start the
	// sign-in (no binding cookie, or another sign-in's): login CSRF.
	ErrBrowser ErrorCode = "browser"
	// ErrProvider: the provider sent the browser back with an error of its
	// own (the person cancelled, or the provider refused them).
	ErrProvider ErrorCode = "provider"
	// ErrToken: the code exchange failed or the id_token did not verify.
	ErrToken ErrorCode = "token"
	// ErrNoSubject: the verified id_token names no subject.
	ErrNoSubject ErrorCode = "no_subject"
	// ErrUnlinked: the identity is linked to no person.
	ErrUnlinked ErrorCode = "unlinked"
	// ErrDisabled: the linked person's account is disabled.
	ErrDisabled ErrorCode = "disabled"
	// ErrSession: a self-link's callback no longer carries the session that
	// started it.
	ErrSession ErrorCode = "session"
	// ErrAlreadyLinked: a self-link names an identity another person holds.
	ErrAlreadyLinked ErrorCode = "already_linked"
	// ErrFailed: anything else (a storage error); try again.
	ErrFailed ErrorCode = "failed"
)

// ErrorCodes is every refusal code, in the order the docs list them.
func ErrorCodes() []ErrorCode {
	return []ErrorCode{ErrNotConfigured, ErrUnreachable, ErrState, ErrBrowser, ErrProvider, ErrToken,
		ErrNoSubject, ErrUnlinked, ErrDisabled, ErrSession, ErrAlreadyLinked, ErrFailed}
}

// ErrorCodesTS is the console's copy of the codes (web/src/lib/sso_errors.gen.ts,
// written by cmd/identitygen on make gen): the console's messages are keyed by
// this union, so a code added here fails the web typecheck until it has one.
func ErrorCodesTS() []byte {
	var b strings.Builder
	b.WriteString("// Generated by cmd/identitygen from internal/sso (make gen). Do not edit.\n")
	b.WriteString("// The closed set of ?sso_error= codes a refused single sign-on comes back with (#2362).\n")
	b.WriteString("// lib/ssoErrors.ts maps each to its fixed message; any other value shows the generic one.\n\n")
	b.WriteString("export const SSO_ERROR_CODES = [\n")
	for _, c := range ErrorCodes() {
		fmt.Fprintf(&b, "  %q,\n", string(c))
	}
	b.WriteString("] as const;\n\n")
	b.WriteString("export type SSOErrorCode = (typeof SSO_ERROR_CODES)[number];\n")
	return []byte(b.String())
}
