// Package simfamilygen writes the registry of the simulator's Go device
// families (#2829): the generated sim/device/families_gen.go, built by
// scanning sim/device/* for the family packages that exist, so the list is
// never hand-kept. A family package is a directory under sim/device whose
// non-test Go files declare `func Spec() spec.Spec`.
package simfamilygen

import (
	"bytes"
	"fmt"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Family is one family package found.
type Family struct {
	// Dir is the directory name under sim/device, and the import path's last
	// element.
	Dir string
	// Name is the package's name.
	Name string
}

// skipped are directories under sim/device that hold no family: the Go
// convention for fixtures and internals.
func skipped(name string) bool {
	return name == "internal" || name == "testdata" || strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_")
}

// Scan lists the family packages under root (sim/device), by directory. A
// directory that holds Go code and no `func Spec() spec.Spec` is an error: a
// family package that registered nothing would be silently absent.
func Scan(root string) ([]Family, error) {
	entries, err := os.ReadDir(root)
	if err != nil {
		return nil, fmt.Errorf("simfamilygen: read %s: %w", root, err)
	}
	var out []Family
	for _, e := range entries {
		if !e.IsDir() || skipped(e.Name()) {
			continue
		}
		dir := filepath.Join(root, e.Name())
		fam, ok, err := inspect(dir)
		if err != nil {
			return nil, err
		}
		if !ok {
			return nil, fmt.Errorf("simfamilygen: %s declares no `func Spec() spec.Spec`, so it is no family; remove it or add one", dir)
		}
		fam.Dir = e.Name()
		out = append(out, fam)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Dir < out[j].Dir })
	return out, nil
}

// inspect reads one directory's non-test Go files for the family's Spec func.
func inspect(dir string) (Family, bool, error) {
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, dir, func(fi os.FileInfo) bool {
		return !strings.HasSuffix(fi.Name(), "_test.go")
	}, 0)
	if err != nil {
		return Family{}, false, fmt.Errorf("simfamilygen: parse %s: %w", dir, err)
	}
	for name, pkg := range pkgs {
		for _, f := range pkg.Files {
			for _, d := range f.Decls {
				fd, ok := declFunc(d)
				if ok && fd.Name == "Spec" && fd.Recv == nil && fd.Params == 0 && fd.Results == 1 {
					return Family{Name: name}, true, nil
				}
			}
		}
	}
	return Family{}, false, nil
}

// Render is the generated source of the registry for the families.
func Render(modulePath string, fams []Family) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/familygen; DO NOT EDIT.\n\n")
	b.WriteString("package device\n\n")
	if len(fams) > 0 {
		b.WriteString("import (\n")
		b.WriteString("\t\"github.com/hyperscaleav/omniglass/sim/spec\"\n\n")
		for _, f := range fams {
			fmt.Fprintf(&b, "\t%s %q\n", alias(f), modulePath+"/sim/device/"+f.Dir)
		}
		b.WriteString(")\n\n")
	} else {
		b.WriteString("import \"github.com/hyperscaleav/omniglass/sim/spec\"\n\n")
	}
	b.WriteString("// families is every Go device family under sim/device, by directory.\n")
	b.WriteString("func families() []spec.Spec {\n")
	if len(fams) == 0 {
		b.WriteString("\treturn nil\n")
	} else {
		b.WriteString("\treturn []spec.Spec{\n")
		for _, f := range fams {
			fmt.Fprintf(&b, "\t\t%s.Spec(),\n", alias(f))
		}
		b.WriteString("\t}\n")
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("simfamilygen: format: %w", err)
	}
	return out, nil
}

// alias is the import name of a family: its directory, which is unique, with
// anything not an identifier character made one.
func alias(f Family) string {
	return "fam_" + strings.Map(func(r rune) rune {
		if r == '_' || (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') {
			return r
		}
		return '_'
	}, f.Dir)
}
