// This file is the system page load (#1632): the reads the console's system
// page makes on a cold open, timed end to end under concurrent clients. The
// fleet view read times one query; an operator opening a system waits on all
// of the page's reads at once, so this is the latency they feel.

// SystemPageReads is every read a cold open of the console's system page
// makes, as paths under /api/v1. {system} is the system's id. The metrics
// read's answer names the series the page charts: one samples read for each
// metric from the contract or sampled, the sampled ones with their instance.
// The page's own test (web/src/pages/SystemZoom.test.tsx) records the reads a
// render makes and compares them to the generated copy of this list, so a
// read the page gains or drops fails there until this list follows.
var SystemPageReads = []string{
	"/auth/me",
	"/component-types",
	"/components",
	"/location-types",
	"/locations",
	"/products",
	"/severity-levels",
	"/standards",
	"/systems",
	"/systems/{system}/health",
	"/systems/{system}/members",
	"/systems/{system}/metrics",
	pageSeriesRead,
	pageSeriesRead + "&instance={instance}",
	"/systems/{system}/roles",
	"/views/fleet",
}

// pageSeriesRead is one chart's samples read: the page's 24 hour range at its
// five minute resolution.
const pageSeriesRead = "/systems/{system}/metrics/{metric}/samples?hours=24&resolution=300"

// SystemPageReadsTS renders SystemPageReads for the console's test
// (web/src/lib/system_page_reads.gen.ts, written by make gen);
// TestSystemPageReadsMatchCommitted is its drift gate.
func SystemPageReadsTS() []byte {
	var b strings.Builder
	b.WriteString("// Generated by cmd/labgen from internal/labfootprint (make gen). Do not edit.\n")
	b.WriteString("// The reads `omniglass lab measure` times as one system page load (#1632): every read a\n")
	b.WriteString("// cold open of the system page makes, as paths under /api/v1. SystemZoom.test.tsx checks\n")
	b.WriteString("// the page makes exactly these, so the lab's load cannot drift from the page.\n\n")
	b.WriteString("export const SYSTEM_PAGE_READS: readonly string[] = [\n")
	for _, r := range SystemPageReads {
		fmt.Fprintf(&b, "  %q,\n", r)
	}
	b.WriteString("];\n")
	return []byte(b.String())
}

// PageLoad is one timed load of the system page: every read, from the first
// request to the last answer. Err is the first read that failed; a failed
// load's time is not a page load and stays out of the quantiles.
type PageLoad struct {
	Took  time.Duration
	Bytes int64
	Err   error
}

// PageRun is the system page loads a window made: Clients loading at once,
// each its share of Loads. No clients means the load was not measured.
type PageRun struct {
	Clients int
	Loads   []PageLoad
}

// SystemPageFigures is the system page load's report: the successful loads'
// milliseconds, their mean bytes, and the failed loads as a loss ratio, 0
// when every load answered.
type SystemPageFigures struct {
	Ms         Quantiles `json:"system_page_ms"`
	Bytes      float64   `json:"system_page_bytes"`
	Clients    int       `json:"system_page_clients"`
	Errors     int       `json:"system_page_errors"`
	ErrorRatio float64   `json:"system_page_error_ratio"`
}

// SummarizePage is the figures of a window's loads, or nil when no client
// loaded the page, so the report leaves the fields out.
func SummarizePage(r PageRun) *SystemPageFigures {
	if r.Clients == 0 {
		return nil
	}
	f := &SystemPageFigures{Clients: r.Clients}
	var took []time.Duration
	var bytes int64
	for _, l := range r.Loads {
		if l.Err != nil {
			f.Errors++
			continue
		}
		took = append(took, l.Took)
		bytes += l.Bytes
	}
	f.Ms = DurationQuantiles(took)
	if len(took) > 0 {
		f.Bytes = float64(bytes) / float64(len(took))
	}
	if len(r.Loads) > 0 {
		f.ErrorRatio = float64(f.Errors) / float64(len(r.Loads))
	}
	return f
}

// describe is the p95 row's account of the loads.
func (f *SystemPageFigures) describe() string {
	return fmt.Sprintf("   (%s loads, %d clients, %d failed, %s a load)",
		count(float64(f.Ms.N)), f.Clients, f.Errors, size(f.Bytes))
}

// pageMetric is the part of a system's effective metric the page charts by.
type pageMetric struct {
	Name         string `json:"metric_type_name"`
	IsSampled    bool   `json:"is_sampled"`
	FromContract bool   `json:"from_contract"`
	Instance     string `json:"instance"`
}

// seriesRead is the samples read the page makes for m, or "" when the page
// does not chart it.
func (m pageMetric) seriesRead() string {
	if !m.FromContract && !m.IsSampled {
		return ""
	}
	r := strings.Replace(pageSeriesRead, "{metric}", url.PathEscape(m.Name), 1)
	if m.IsSampled {
		r += "&instance=" + url.QueryEscape(m.Instance)
	}
	return r
}

// loadSystemPage loads the system page once against base, as a cold open
// does: every read at once, the series reads as soon as the metrics read
// names them. The load fails on the first read that does not answer 200.
func (h *harness) loadSystemPage(ctx context.Context, base, systemID string) PageLoad {
	start := time.Now()
	var (
		mu    sync.Mutex
		wg    sync.WaitGroup
		bytes int64
		first error
	)
	read := func(path string) []byte {
		code, status, body, err := h.fetch(ctx, base+"/api/v1"+path)
		mu.Lock()
		defer mu.Unlock()
		bytes += int64(len(body))
		if err == nil && code != http.StatusOK {
			err = statusError(status, body)
		}
		if err != nil {
			if first == nil {
				first = fmt.Errorf("GET %s: %w", path, err)
			}
			return nil
		}
		return body
	}
	sys := url.PathEscape(systemID)
	for _, r := range SystemPageReads {
		if strings.Contains(r, "{metric}") {
			continue
		}
		path := strings.ReplaceAll(r, "{system}", sys)
		wg.Add(1)
		go func() {
			defer wg.Done()
			body := read(path)
			if body == nil || !strings.HasSuffix(path, "/metrics") {
				return
			}
			var list struct {
				Metrics []pageMetric `json:"metrics"`
			}
			if err := json.Unmarshal(body, &list); err != nil {
				mu.Lock()
				if first == nil {
					first = fmt.Errorf("GET %s: %w", path, err)
				}
				mu.Unlock()
				return
			}
			for _, m := range list.Metrics {
				s := m.seriesRead()
				if s == "" {
					continue
				}
				s = strings.ReplaceAll(s, "{system}", sys)
				wg.Add(1)
				go func() {
					defer wg.Done()
					read(s)
				}()
			}
		}()
	}
	wg.Wait()
	return PageLoad{Took: time.Since(start), Bytes: bytes, Err: first}
}

// PickPageSystem is the id of the system the page load opens, from the fleet
// view's answer: the one named, or with no name the view's first.
func PickPageSystem(fleetView []byte, name string) (string, error) {
	var v struct {
		Systems []struct {
			ID   string `json:"id"`
			Name string `json:"name"`
		} `json:"systems"`
	}
	if err := json.Unmarshal(fleetView, &v); err != nil {
		return "", fmt.Errorf("read the fleet view's systems: %w", err)
	}
	if len(v.Systems) == 0 {
		return "", errors.New("the fleet view lists no systems, so there is no system page to load")
	}
	if name == "" {
		return v.Systems[0].ID, nil
	}
	for _, s := range v.Systems {
		if s.Name == name {
			return s.ID, nil
		}
	}
	return "", fmt.Errorf("--page-system %q: the fleet view lists no system of that name", name)
}
