// exactFamilies is the figures that must read 0, in the order the verdict
// lists them.
func exactFamilies() []exactFamily {
	return []exactFamily{
		{Family: "closed_loop_loss", About: "every closed-loop gap from endpoint to database (#1639), per gap",
			Read: func(r ScaleReport) []exactReading {
				var out []exactReading
				for _, g := range closedloop.GapNames() {
					name := "closed_loop_loss/" + g
					if r.Endpoints == nil {
						out = append(out, exactReading{Name: name, Missing: true, Note: "not measured: " + cmpOr(r.EndpointsGap, "the closed loop was not read")})
						continue
					}
					i := slices.IndexFunc(r.Endpoints.GapTotals, func(t closedloop.GapTotal) bool { return t.Gap == g })
					if i < 0 {
						out = append(out, exactReading{Name: name, Missing: true, Note: "not measured: no total for the gap"})
						continue
					}
					out = append(out, exactReading{Name: name, Value: float64(r.Endpoints.GapTotals[i].Loss)})
				}
				return out
			}},
		{Family: "ingest_lag_not_measured", About: "1 when no sample probed in the window had landed by its end",
			Read: func(r ScaleReport) []exactReading {
				if r.IngestLagGap != nil {
					return []exactReading{{Name: "ingest_lag_not_measured", Value: 1, Note: r.IngestLagGap.Reason}}
				}
				return []exactReading{{Name: "ingest_lag_not_measured"}}
			}},
		{Family: "redeliveries", About: "telemetry batches the server logged as redelivered or abandoned",
			Read: func(r ScaleReport) []exactReading {
				return []exactReading{{Name: "redeliveries", Value: float64(r.Redeliveries.Total())}}
			}},
		{Family: "delivery_loss", About: "each telemetry kind's loss across each hop (#1641), per hop and kind",
			Read: func(r ScaleReport) []exactReading {
				if r.DeliveryNotRead != "" {
					return []exactReading{{Name: "delivery_loss", Missing: true, Note: "not measured: " + r.DeliveryNotRead}}
				}
				var out []exactReading
				for _, d := range r.Delivery {
					if d.Loss != nil {
						out = append(out, exactReading{Name: deliveryFigure(d), Value: *d.Loss, Note: lossNote(d)})
					}
				}
				// A read with no kind to account is not a 0: a fleet that
				// delivered nothing in the window lost everything it sent.
				if len(out) == 0 {
					return []exactReading{{Name: "delivery_loss", Missing: true, Note: "not measured: no telemetry kind carried items in the window"}}
				}
				return out
			}},
		{Family: "delivery_unsettled_boots", About: "node boots whose batches had not all settled when the read ran out",
			Read: func(r ScaleReport) []exactReading {
				return []exactReading{{Name: "delivery_unsettled_boots", Value: float64(len(r.DeliveryUnsettled)), Note: unsettledNote(r)}}
			}},
	}
}

// deliverySubject is what a delivery row counts: its kind, or on the sim hop,
// whose rows are one a protocol with no kind (#1694), its protocol.
func deliverySubject(d DeliveryRow) string {
	if d.Hop == delivery.Sim {
		return d.Protocol
	}
	return string(d.Kind)
}

// deliveryFigure is a delivery row's exact figure name,
// delivery_loss/<hop>/<kind>, the sim hop's naming its protocol in place of
// the kind. A push-lane row (#1696) names its lane first, so it is never
// folded into the node lane's row for the same hop and kind.
func deliveryFigure(d DeliveryRow) string {
	if d.Lane == LanePush {
		return fmt.Sprintf("delivery_loss/%s/%s/%s", d.Lane, d.Hop, deliverySubject(d))
	}
	return fmt.Sprintf("delivery_loss/%s/%s", d.Hop, deliverySubject(d))
}

// lossNote names a lossy delivery row's kind (or protocol), hop and cause,
// with its lane when it is the push lane's, empty when the row lost nothing.
func lossNote(d DeliveryRow) string {
	if d.Lost() == 0 {
		return ""
	}
	at := string(d.Hop)
	if d.Lane == LanePush {
		at += " on the push lane"
	}
	return fmt.Sprintf("%s lost %d of %d at %s, cause %s", deliverySubject(d), d.Lost(), d.In, at, cmpOr(string(d.Cause()), "unknown"))
}

// unsettledNamed is how many unsettled boots a note names before it counts
// the rest.
const unsettledNamed = 3

// unsettledNote names the run's unsettled boots, the first few by node and
// boot, with the read's own note on why, empty when every boot settled.
func unsettledNote(r ScaleReport) string {
	if len(r.DeliveryUnsettled) == 0 {
		return ""
	}
	var named []string
	for _, u := range r.DeliveryUnsettled[:min(len(r.DeliveryUnsettled), unsettledNamed)] {
		named = append(named, fmt.Sprintf("node %s boot %s", u.Node, u.Boot))
	}
	note := "no ratio read from " + strings.Join(named, ", ")
	if more := len(r.DeliveryUnsettled) - unsettledNamed; more > 0 {
		note += fmt.Sprintf(" and %d more", more)
	}
	if r.DeliveryNote != "" {
		note += "; " + r.DeliveryNote
	}
	return note
}

func cmpOr(s, or string) string {
	if s == "" {
		return or
	}
	return s
}

// FigureVerdict is one figure's comparison. Observed is the runs' median
// (the worst run, for an exact figure); Delta is Observed less Baseline, and
// DeltaRatio that over the baseline.
type FigureVerdict struct {
	Name           string     `json:"name"`
	Family         string     `json:"family"`
	Class          PerfClass  `json:"class"`
	Status         PerfStatus `json:"status"`
	Baseline       float64    `json:"baseline"`
	Observed       float64    `json:"observed"`
	Delta          float64    `json:"delta"`
	DeltaRatio     float64    `json:"delta_ratio"`
	BaselineSpread float64    `json:"baseline_spread"`
	Spread         float64    `json:"spread"`
	Tolerance      float64    `json:"tolerance"`
	Note           string     `json:"note,omitempty"`
}

// PerfVerdict is a check: invalid, fail, noisy or pass, with every figure.
type PerfVerdict struct {
	Status       PerfStatus      `json:"status"`
	Size         string          `json:"size"`
	Runs         int             `json:"runs"`
	Invalid      []string        `json:"invalid,omitempty"`
	BaselineHost Fingerprint     `json:"baseline_host"`
	Host         *Fingerprint    `json:"host,omitempty"`
	HostMatch    bool            `json:"host_match"`
	Figures      []FigureVerdict `json:"figures,omitempty"`
}

// Failed is whether the check exits nonzero: on a fail or an invalid run.
// A noisy check does not fail.
func (v PerfVerdict) Failed() bool { return v.Status == PerfFail || v.Status == PerfInvalid }

// ComparePerf compares fresh runs with a baseline. It refuses runs that are
// not clean or not the baseline's fleet before any figure is compared.
func ComparePerf(base Baseline, runs []ScaleReport, tol Tolerances) PerfVerdict {
	v := PerfVerdict{Size: base.Inputs.Size, Runs: len(runs), BaselineHost: base.Host}
	if reasons := invalidRuns(base.Inputs, runs); len(reasons) > 0 {
		v.Status, v.Invalid = PerfInvalid, reasons
		return v
	}
	host, one := runsHost(runs)
	v.Host = host
	v.HostMatch = one && host != nil && base.Host.SameMachine(*host)
	v.Figures = append(exactVerdicts(runs), gatedVerdicts(base, runs, tol, v.HostMatch)...)
	slices.SortStableFunc(v.Figures, func(a, b FigureVerdict) int { return statusRank(a.Status) - statusRank(b.Status) })
	v.Status = PerfPass
	for _, f := range v.Figures {
		switch {
		case f.Status == PerfFail:
			v.Status = PerfFail
		case f.Status == PerfNoisy && v.Status == PerfPass:
			v.Status = PerfNoisy
		}
	}
	return v
}

// statusRank orders the verdict's rows: failed first, then noisy, then the
// rest in table order.
func statusRank(s PerfStatus) int {
	switch s {
	case PerfFail:
		return 0
	case PerfNoisy:
		return 1
	}
	return 2
}

// invalidRuns is why the runs cannot be compared with a baseline measured
// with in, each reason once with the runs it holds for.
func invalidRuns(in PerfInputs, runs []ScaleReport) []string {
	if len(runs) == 0 {
		return []string{"no runs to compare"}
	}
	// The device set is checked on both sides: a baseline or a run that
	// names none cannot be said to measure the other's fleet.
	if in.PlanDigest == "" {
		return []string{"the baseline names no device set: regenerate it with lab perf baseline"}
	}
	var order []string
	byReason := map[string][]string{}
	add := func(i int, reason string) {
		if _, ok := byReason[reason]; !ok {
			order = append(order, reason)
		}
		byReason[reason] = append(byReason[reason], strconv.Itoa(i+1))
	}
	window := func(s int) string { return (time.Duration(s) * time.Second).String() }
	for i, r := range runs {
		if r.Scenario != in.Scenario || r.Systems != in.Systems {
			add(i, fmt.Sprintf("the run measured %s at %d systems; the baseline is %s at %d", r.Scenario, r.Systems, in.Scenario, in.Systems))
		}
		if r.WindowS != in.WindowS || r.WarmupS != in.WarmupS {
			add(i, fmt.Sprintf("the run measured a %s window after %s; the baseline a %s window after %s",
				window(r.WindowS), window(r.WarmupS), window(in.WindowS), window(in.WarmupS)))
		}
		switch {
		case r.PlanDigest == "":
			add(i, "the run recorded no device set (a series from before the gate, or a scenario this build could not plan)")
		case r.PlanDigest != in.PlanDigest:
			add(i, "this build places a different device set than the baseline's: regenerate the baseline")
		}
		if r.Endpoints == nil {
			continue
		}
		for _, n := range r.Endpoints.Nodes {
			if n.Restarted {
				add(i, fmt.Sprintf("node %s restarted during the window", n.Node))
			}
			if n.Impaired {
				add(i, fmt.Sprintf("node %s carried an impairment: a gated lab is never impaired, so a fault was left on", n.Node))
			}
		}
		for _, g := range r.Endpoints.GapTotals {
			if g.Impaired > 0 {
				add(i, fmt.Sprintf("gap %s read %d impaired: a gated lab is never impaired, so a fault was left on", g.Gap, g.Impaired))
			}
		}
	}
	out := make([]string, len(order))
	for i, reason := range order {
		runs := byReason[reason]
		label := "run"
		if len(runs) > 1 {
			label = "runs"
		}
		out[i] = fmt.Sprintf("%s (%s %s)", reason, label, strings.Join(runs, ", "))
	}
	return out
}

// runsHost is the runs' host, and whether every run ran on that one machine.
func runsHost(runs []ScaleReport) (*Fingerprint, bool) {
	if len(runs) == 0 || runs[0].Host == nil {
		return nil, false
	}
	for _, r := range runs[1:] {
		if r.Host == nil || !r.Host.SameMachine(*runs[0].Host) {
			return runs[0].Host, false
		}
	}
	return runs[0].Host, true
}

// exactVerdicts reads every exact figure on every run: the worst run is the
// figure, and anything but 0 fails.
func exactVerdicts(runs []ScaleReport) []FigureVerdict {
	var out []FigureVerdict
	for _, fam := range exactFamilies() {
		var names []string
		worst := map[string]*FigureVerdict{}
		missing := map[string]int{}
		for _, r := range runs {
			for _, x := range fam.Read(r) {
				f, ok := worst[x.Name]
				if !ok {
					names = append(names, x.Name)
					f = &FigureVerdict{Name: x.Name, Family: fam.Family, Class: ClassExact, Status: PerfPass}
					worst[x.Name] = f
				}
				switch {
				case x.Missing:
					missing[x.Name]++
					f.Note = x.Note
				case x.Value > f.Observed:
					// The worst run says why, unless a run that could not
					// be read already has.
					f.Observed = x.Value
					if missing[x.Name] == 0 {
						f.Note = x.Note
					}
				}
			}
		}
		for _, n := range names {
			f := worst[n]
			if missing[n] > 0 || f.Observed != 0 {
				f.Status = PerfFail
			}
			f.Delta = f.Observed
			out = append(out, *f)
		}
	}
	return out
}

func toleranceOf(fam gatedFamily, tol Tolerances) float64 {
	if t, ok := tol[fam.Family]; ok {
		return t
	}
	return fam.Tolerance
}

// gatedValues is each run's value of each figure of the family, by name, in
// the order names first appear; a run that did not measure a name has no
// value for it.
func gatedValues(fam gatedFamily, runs []ScaleReport) ([]string, map[string][]float64) {
	var names []string
	vals := map[string][]float64{}
	for _, r := range runs {
		got := fam.Read(r)
		keys := make([]string, 0, len(got))
		for k := range got {
			keys = append(keys, k)
		}
		slices.Sort(keys)
		for _, k := range keys {
			if _, ok := vals[k]; !ok {
				names = append(names, k)
			}
			vals[k] = append(vals[k], got[k])
		}
	}
	return names, vals
}

func gatedVerdicts(base Baseline, runs []ScaleReport, tol Tolerances, hostMatch bool) []FigureVerdict {
	inBase := map[string]BaselineFigure{}
	for _, f := range base.Figures {
		inBase[f.Name] = f
	}
	var out []FigureVerdict
	for _, fam := range gatedFamilies() {
		t := toleranceOf(fam, tol)
		gates := fam.Class == ClassHostIndependent || hostMatch
		names, vals := gatedValues(fam, runs)
		var baseNames []string
		for _, f := range base.Figures {
			if f.Name == fam.Family || strings.HasPrefix(f.Name, fam.Family+"/") {
				baseNames = append(baseNames, f.Name)
			}
		}
		for _, n := range names {
			if !slices.Contains(baseNames, n) {
				baseNames = append(baseNames, n)
			}
		}
		for _, n := range baseNames {
			fv := FigureVerdict{Name: n, Family: fam.Family, Class: fam.Class, Tolerance: t}
			got := vals[n]
			if len(got) > 0 {
				fv.Observed, fv.Spread = medianSpread(got)
			}
			b, held := inBase[n]
			if !held {
				fv.Status, fv.Note = PerfReported, "not in the baseline"
				out = append(out, fv)
				continue
			}
			fv.Baseline, fv.BaselineSpread = b.Median, b.Spread
			if len(got) < len(runs) {
				fv.Note = fmt.Sprintf("not measured in %d of %d runs", len(runs)-len(got), len(runs))
				fv.Status = PerfReported
				if gates {
					fv.Status = PerfFail
				}
				out = append(out, fv)
				continue
			}
			fv.Delta = fv.Observed - b.Median
			if b.Median != 0 {
				fv.DeltaRatio = fv.Delta / math.Abs(b.Median)
			}
			if !gates {
				fv.Status, fv.Note = PerfReported, "another host than the baseline's"
				out = append(out, fv)
				continue
			}
			fv.Status, fv.Note = judge(fv, fam.TwoSided)
			out = append(out, fv)
		}
	}
	return out
}

// judge is a gated figure's status. It fails only when the median is past
// the tolerance and past the combined spread (the baseline's runs' plus the
// fresh runs'), so a figure whose own noise could hold the excess passes.
// Fresh runs that spread past the tolerance could not have seen a regression
// of that size, so read noisy rather than pass.
func judge(f FigureVerdict, twoSided bool) (PerfStatus, string) {
	tolAbs := f.Tolerance * math.Abs(f.Baseline)
	excess := f.Delta
	if twoSided {
		excess = math.Abs(f.Delta)
	}
	switch {
	case excess > tolAbs && excess > f.BaselineSpread+f.Spread:
		return PerfFail, fmt.Sprintf("past its %s tolerance and the runs' combined spread", pct(f.Tolerance))
	case f.Spread > tolAbs:
		return PerfNoisy, fmt.Sprintf("the runs spread %s, past the %s tolerance: a regression this size could not be seen", num(f.Spread), pct(f.Tolerance))
	case !twoSided && -f.Delta > tolAbs:
		return PerfImproved, "better than its tolerance: refresh the baseline"
	}
	return PerfPass, ""
}

// medianSpread is the median of xs and its spread, max less min.
func medianSpread(xs []float64) (float64, float64) {
	s := slices.Clone(xs)
	slices.Sort(s)
	n := len(s)
	med := s[n/2]
	if n%2 == 0 {
		med = (s[n/2-1] + s[n/2]) / 2
	}
	return med, s[n-1] - s[0]
}

// GenerateBaseline makes a baseline from runs measured with in. It refuses
// runs that are not clean, not in's fleet, or not from one known host; a run
// with an exact figure that is not 0; and, naming each, a gated figure whose
// runs spread past its tolerance, which a check could never gate.
func GenerateBaseline(in PerfInputs, runs []ScaleReport, tol Tolerances) (Baseline, error) {
	if reasons := invalidRuns(in, runs); len(reasons) > 0 {
		return Baseline{}, fmt.Errorf("the runs cannot make a baseline: %s", strings.Join(reasons, "; "))
	}
	host, one := runsHost(runs)
	switch {
	case host == nil:
		return Baseline{}, errors.New("the runs carry no host fingerprint (the lab ran on a daemon that is not this host): a baseline names its host")
	case !one:
		return Baseline{}, errors.New("the runs ran on more than one host: a baseline is one host's")
	}
	var bad []string
	for _, f := range exactVerdicts(runs) {
		if f.Status != PerfPass {
			bad = append(bad, fmt.Sprintf("%s reads %s %s", f.Name, num(f.Observed), f.Note))
		}
	}
	if len(bad) > 0 {
		return Baseline{}, fmt.Errorf("an exact figure is not 0, so the lab is not healthy enough to baseline: %s", strings.Join(bad, "; "))
	}
	b := Baseline{Inputs: in, Host: *host, Runs: len(runs)}
	b.Host.Build = runs[0].Build
	for _, fam := range gatedFamilies() {
		t := toleranceOf(fam, tol)
		names, vals := gatedValues(fam, runs)
		for _, n := range names {
			got := vals[n]
			if len(got) < len(runs) {
				bad = append(bad, fmt.Sprintf("%s was measured in %d of %d runs", n, len(got), len(runs)))
				continue
			}
			med, spread := medianSpread(got)
			if spread > t*math.Abs(med) {
				bad = append(bad, fmt.Sprintf("%s spread %s over a median of %s, past its %s tolerance", n, num(spread), num(med), pct(t)))
				continue
			}
			b.Figures = append(b.Figures, BaselineFigure{Name: n, Median: med, Spread: spread, Values: got})
		}
	}
	if len(bad) > 0 {
		return Baseline{}, fmt.Errorf("refusing to write the baseline: %s", strings.Join(bad, "; "))
	}
	return b, nil
}

// ReadSampleReports reads a sampling run's series (#1632) and returns the
// reports of its last n samples, refusing a failed sample among them.
func ReadSampleReports(r io.Reader, n int) ([]ScaleReport, error) {
	if n <= 0 {
		return nil, fmt.Errorf("read the last %d samples: want at least 1", n)
	}
	var samples []ScaleSample
	sc := bufio.NewScanner(r)
	sc.Buffer(make([]byte, 0, 64<<10), 16<<20)
	for sc.Scan() {
		line := bytes.TrimSpace(sc.Bytes())
		if len(line) == 0 {
			continue
		}
		var s ScaleSample
		if err := json.Unmarshal(line, &s); err != nil {
			return nil, fmt.Errorf("read sample %d: %w", len(samples)+1, err)
		}
		samples = append(samples, s)
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	if len(samples) < n {
		return nil, fmt.Errorf("the series holds %d samples; the check reads the last %d", len(samples), n)
	}
	var out []ScaleReport
	for _, s := range samples[len(samples)-n:] {
		switch {
		case s.Error != "":
			return nil, fmt.Errorf("sample %d failed (%s): the last %d samples are not all figures", s.Seq, s.Error, n)
		case s.ScaleReport == nil:
			return nil, fmt.Errorf("sample %d carries no report", s.Seq)
		}
		out = append(out, *s.ScaleReport)
	}
	return out, nil
}

// WriteTable writes the verdict as the check prints it: the status, then
// each figure, failed and noisy rows first.
func (v PerfVerdict) WriteTable(w io.Writer) {
	fmt.Fprintf(w, "perf gate: %s (size %s, %d runs)\n", v.Status, v.Size, v.Runs)
	for _, r := range v.Invalid {
		fmt.Fprintf(w, "invalid: %s\n", r)
	}
	if len(v.Invalid) > 0 {
		return
	}
	switch {
	case v.HostMatch:
		fmt.Fprintf(w, "host: %s, the baseline's: every figure gates\n", v.Host)
	case v.Host == nil:
		fmt.Fprintf(w, "host: unknown; the baseline's is %s: host-dependent figures are reported, not gated\n", v.BaselineHost)
	default:
		fmt.Fprintf(w, "host: %s; the baseline's is %s: host-dependent figures are reported, not gated\n", v.Host, v.BaselineHost)
	}
	tw := tabwriter.NewWriter(w, 0, 0, 2, ' ', 0)
	fmt.Fprintln(tw, "STATUS\tFIGURE\tCLASS\tBASELINE\tOBSERVED\tDELTA\tSPREAD (BASE/RUNS)\tTOLERANCE\tNOTE")
	for _, f := range v.Figures {
		delta, spread, tol := num(f.Delta), "-", "0"
		if f.Class != ClassExact {
			if f.Baseline != 0 {
				delta = fmt.Sprintf("%+.1f%%", f.DeltaRatio*100)
			}
			spread = num(f.BaselineSpread) + "/" + num(f.Spread)
			tol = pct(f.Tolerance)
		}
		fmt.Fprintf(tw, "%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n", f.Status, f.Name, f.Class, num(f.Baseline), num(f.Observed), delta, spread, tol, f.Note)
	}
	tw.Flush()
}

func pct(f float64) string { return strconv.FormatFloat(f*100, 'f', -1, 64) + "%" }

// num prints a figure at a precision a reader compares by eye.
func num(f float64) string {
	if math.Abs(f) >= 1e5 {
		return strconv.FormatFloat(f, 'f', 0, 64)
	}
	return strconv.FormatFloat(f, 'g', 4, 64)
}

// PerfFacts is the gate's tables and sizes, as the docs render them.
type PerfFacts struct {
	Figures []PerfFigureFact `json:"figures"`
	Sizes   []PerfSizeFact   `json:"sizes"`
}

// PerfFigureFact is one figure family: its class, the tolerance it gates at
// (0 for the exact class, which must read 0) and whether it is two-sided.
type PerfFigureFact struct {
	Family    string    `json:"family"`
	Class     PerfClass `json:"class"`
	Tolerance float64   `json:"tolerance"`
	TwoSided  bool      `json:"two_sided"`
	Unit      string    `json:"unit,omitempty"`
	About     string    `json:"about"`
}

// PerfSizeFact is one gated size and its baseline file.
type PerfSizeFact struct {
	Name       string `json:"name"`
	Scenario   string `json:"scenario"`
	Systems    int    `json:"systems"`
	WarmupS    int    `json:"warmup_seconds"`
	WindowS    int    `json:"window_seconds"`
	FleetReads int    `json:"fleet_reads"`
	File       string `json:"file"`
}

// PerfGateFacts is the gate's tables and sizes, for the docs.
func PerfGateFacts() PerfFacts {
	var out PerfFacts
	for _, f := range exactFamilies() {
		out.Figures = append(out.Figures, PerfFigureFact{Family: f.Family, Class: ClassExact, About: f.About})
	}
	for _, f := range gatedFamilies() {
		out.Figures = append(out.Figures, PerfFigureFact{Family: f.Family, Class: f.Class, Tolerance: f.Tolerance,
			TwoSided: f.TwoSided, Unit: f.Unit, About: f.About})
	}
	for _, s := range lab.PerfSizes() {
		out.Sizes = append(out.Sizes, PerfSizeFact{Name: s.Name, Scenario: s.Scenario, Systems: s.Systems,
			WarmupS: int(s.Warmup.Seconds()), WindowS: int(s.Window.Seconds()), FleetReads: s.FleetReads, File: s.BaselineFile()})
	}
	return out
}

// PerfGateFactsJSON is PerfGateFacts as the docs read it
// (docs/src/generated/perfgate.json, written by make gen).
func PerfGateFactsJSON() ([]byte, error) {
	b, err := json.MarshalIndent(PerfGateFacts(), "", "  ")
	if err != nil {
		return nil, err
	}
	return append(b, '\n'), nil
}
