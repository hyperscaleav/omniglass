// The perf gate (#1640, amending ADR-0094): a whole scale lab measured end
// to end and compared with a committed baseline generated on a known host.
// Every figure falls in one of three classes. The exact class must read 0 on
// every run, whatever the baseline holds. The host-independent class (counts
// and bytes a system costs) gates on any host. The host-dependent class
// (time and resources) gates only on the host the baseline was generated on,
// and is reported everywhere else. A gated figure is the median of the runs,
// and fails only when it is past its tolerance and past the noise the runs
// themselves show. The tables below are the gate: changing a tolerance is a
// reviewed code change, never an edit to a baseline file.

// PerfClass is how a figure gates.
type PerfClass string

const (
	// ClassExact must read 0 on every run.
	ClassExact PerfClass = "exact"
	// ClassHostIndependent gates against the baseline on any host.
	ClassHostIndependent PerfClass = "host-independent"
	// ClassHostDependent gates only on the baseline's host.
	ClassHostDependent PerfClass = "host-dependent"
)

// PerfStatus is how a figure, or a whole check, reads.
type PerfStatus string

const (
	PerfPass PerfStatus = "pass"
	PerfFail PerfStatus = "fail"
	// PerfNoisy is a figure whose fresh runs spread past its tolerance: the
	// check could not have seen a regression of that size. It does not fail.
	PerfNoisy PerfStatus = "noisy"
	// PerfReported is a figure shown but not gated: host-dependent on
	// another host, or one the baseline does not hold.
	PerfReported PerfStatus = "reported"
	// PerfImproved is a figure better than its tolerance: refresh the
	// baseline.
	PerfImproved PerfStatus = "improved"
	// PerfInvalid is a check whose runs were not clean, or not the
	// baseline's fleet: no figure was compared.
	PerfInvalid PerfStatus = "invalid"
)

// Fingerprint is the host a lab ran on. Two hosts are the same machine when
// the CPU model, the logical cores and the memory match; the Go version and
// the build are recorded, not matched, since a change to either is what a
// check is for.
type Fingerprint struct {
	CPU       string `json:"cpu"`
	Cores     int    `json:"cores"`
	MemoryGiB int    `json:"memory_gib"`
	Go        string `json:"go"`
	// Build is the image the baseline's runs measured; a run's own build is
	// on its report.
	Build string `json:"build,omitempty"`
}

// SameMachine reports whether f and o are the same class of machine.
func (f Fingerprint) SameMachine(o Fingerprint) bool {
	return f.CPU != "" && f.CPU == o.CPU && f.Cores == o.Cores && f.MemoryGiB == o.MemoryGiB
}

func (f Fingerprint) String() string {
	return fmt.Sprintf("%s, %d cores, %d GiB", f.CPU, f.Cores, f.MemoryGiB)
}

// PerfInputs are what a baseline's runs were measured with; a check measures
// with the same.
type PerfInputs struct {
	Size       string `json:"size"`
	Scenario   string `json:"scenario"`
	Systems    int    `json:"systems"`
	WarmupS    int    `json:"warmup_seconds"`
	WindowS    int    `json:"window_seconds"`
	FleetReads int    `json:"fleet_reads"`
	// PlanDigest is the device set the scenario at its size placed.
	PlanDigest string `json:"plan_digest"`
}

// PerfInputsOf is the inputs a size measures with, with its plan's digest.
func PerfInputsOf(s lab.PerfSize) (PerfInputs, error) {
	digest, err := lab.PerfPlanDigest(s.Scenario, s.Systems)
	if err != nil {
		return PerfInputs{}, err
	}
	return PerfInputs{Size: s.Name, Scenario: s.Scenario, Systems: s.Systems,
		WarmupS: int(s.Warmup.Seconds()), WindowS: int(s.Window.Seconds()),
		FleetReads: s.FleetReads, PlanDigest: digest}, nil
}

// BaselineFigure is one gated figure over the baseline's runs.
type BaselineFigure struct {
	Name   string    `json:"name"`
	Median float64   `json:"median"`
	Spread float64   `json:"spread"`
	Values []float64 `json:"values"`
}

// Baseline is a committed baseline file: generated by `lab perf baseline`,
// never written by hand.
type Baseline struct {
	Inputs  PerfInputs       `json:"inputs"`
	Host    Fingerprint      `json:"host"`
	Runs    int              `json:"runs"`
	Figures []BaselineFigure `json:"figures"`
}

// Write writes the baseline as indented JSON.
func (b Baseline) Write(w io.Writer) error {
	out, err := json.MarshalIndent(b, "", "  ")
	if err != nil {
		return err
	}
	_, err = w.Write(append(out, '\n'))
	return err
}

// ReadBaseline reads a baseline file, refusing one that names a field the
// gate does not know or holds no figure.
func ReadBaseline(r io.Reader) (Baseline, error) {
	dec := json.NewDecoder(r)
	dec.DisallowUnknownFields()
	var b Baseline
	if err := dec.Decode(&b); err != nil {
		return Baseline{}, fmt.Errorf("read baseline: %w", err)
	}
	if b.Inputs.Scenario == "" || len(b.Figures) == 0 {
		return Baseline{}, errors.New("read baseline: it names no scenario or holds no figure")
	}
	return b, nil
}

// Tolerances overrides the table's tolerance for a figure family, as a
// fraction of the baseline's median. Nil is the table's.
type Tolerances map[string]float64

// gatedFamily is a figure family the gate compares with the baseline. Read
// returns each figure the family has in a report, by name; a figure the
// report did not measure is absent.
type gatedFamily struct {
	Family    string
	Class     PerfClass
	Tolerance float64
	// TwoSided figures fail past the tolerance either way: a rate that falls
	// is a change in what the lab does, not an improvement.
	TwoSided bool
	Unit     string
	About    string
	Read     func(ScaleReport) map[string]float64
}

// exactFamily is a figure family that must read 0 on every run.
type exactFamily struct {
	Family string
	About  string
	Read   func(ScaleReport) []exactReading
}

// exactReading is one exact figure in one run. Missing is a figure the run
// could not measure, which fails like a nonzero one.
type exactReading struct {
	Name    string
	Value   float64
	Missing bool
	Note    string
}

func one(name string, v float64) map[string]float64 { return map[string]float64{name: v} }

// perSystem is a figure divided by the run's systems, absent when the run
// counted none.
func perSystem(name string, v float64, r ScaleReport) map[string]float64 {
	if r.Systems <= 0 {
		return nil
	}
	return one(name, v/float64(r.Systems))
}

func positive(name string, v float64) map[string]float64 {
	if v <= 0 {
		return nil
	}
	return one(name, v)
}

func serverContainer(r ScaleReport) (ScaleContainer, bool) {
	for _, c := range r.Containers {
		if c.Name == "server" {
			return c, true
		}
	}
	return ScaleContainer{}, false
}

